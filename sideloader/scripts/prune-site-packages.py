"""Remove packages the Sideloader helper never imports from the bundled site-packages.

KEEP is the union of the top-level modules loaded by the helper's full flow
(sign-in, signing, USB and Wi-Fi tunnel, installing), traced on Windows and Linux.
"""
import shutil
import sys
from pathlib import Path

KEEP = {
    "anisette", "arrow", "backports", "bytestruct", "certifi", "chardet", "charset_normalizer", "click",
    "cryptography", "dateutil", "elftools", "hyperframe", "idna", "ifaddr", "opack2", "packaging",
    "pmd_net_addr", "pmd_net_proto", "pmd_pytcp", "prompt_toolkit", "psutil", "pygments", "pygnuutils",
    "pymobiledevice3", "pytun_pmd3", "qh3", "questionary", "requests", "rich", "six", "srp", "srptools",
    "typing_extensions", "unicorn", "urllib3", "wcwidth", "_cffi_backend",
    # pywin32 (win32security and its DLLs)
    "win32", "pywin32_system32", "pywin32_bootstrap", "pywin32",
}
# Distribution names (dist-info) differ from module names for a few.
DIST = {"python_dateutil": "dateutil", "pyelftools": "elftools", "charset_normalizer": "charset_normalizer",
        "cffi": "_cffi_backend", "pymobiledevice3": "pymobiledevice3", "pywin32": "pywin32",
        "typing_extensions": "typing_extensions"}

site = Path(sys.argv[1])
before = sum(1 for _ in site.rglob("*") if _.is_file())
for entry in site.iterdir():
    name = entry.name
    if name.endswith(".dist-info"):
        dist = name.split("-")[0].lower().replace("-", "_")
        if dist in KEEP or DIST.get(dist) in KEEP:
            continue
    elif name.endswith(".pth"):
        if name.startswith("pywin32"):
            continue
    else:
        top = name.split(".")[0]
        if top in KEEP or "__mypyc" in name:  # charset_normalizer's compiled helper
            continue
    shutil.rmtree(entry) if entry.is_dir() else entry.unlink()
# Tests and type stubs aren't needed at run time.
for d in list(site.rglob("tests")) + list(site.rglob("test")):
    if d.is_dir() and "pymobiledevice3" not in d.parts[-2:]:
        shutil.rmtree(d, ignore_errors=True)
after = sum(1 for _ in site.rglob("*") if _.is_file())
print(f"site-packages: {before} -> {after} files")
